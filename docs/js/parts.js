// Перерисовка списка при смене языка; раскрытые пункты остаются раскрытыми
function renderParts() {
  const box = $('#plist');
  const open = [...box.querySelectorAll('details')].map((d) => d.open);
  box.innerHTML = PARTS.map((p, i) => {
    const L = p[LANG];
    return `<details${p.sub ? ' class="sub"' : ''}${open[i] ? ' open' : ''}>` +
      `<summary><span class="pn"><b>${L.n}</b><span class="hint">${L.h}</span></span>` +
      `<span class="num">${p.ali}</span><span class="num">${p.shop}</span><span class="chev" aria-hidden="true"></span></summary>` +
      `<div class="pbody"><p><b>${t(p.sub ? 'parts.what' : 'parts.why')}</b> ${L.why}</p>` +
      `<ul>${L.alts.map((a) => `<li>${a}</li>`).join('')}</ul></div></details>`;
  }).join('');
}
